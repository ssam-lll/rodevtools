CREATE TABLE IF NOT EXISTS games (
    universe_id BIGINT PRIMARY KEY,
    root_place_id BIGINT,
    name VARCHAR(255) NOT NULL,
    description TEXT,
    visits BIGINT,
    playing BIGINT,
    likes BIGINT,
    dislikes BIGINT,
    rating DOUBLE PRECISION,
    creator_name VARCHAR(255),
    creator_id BIGINT,
    roblox_created_at TIMESTAMP(6),
    roblox_updated_at TIMESTAMP(6),
    category VARCHAR(255),
    last_synced_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_games_root_place_id ON games (root_place_id);
CREATE INDEX IF NOT EXISTS idx_games_playing ON games (playing);
CREATE INDEX IF NOT EXISTS idx_games_last_synced_at ON games (last_synced_at);
CREATE INDEX IF NOT EXISTS idx_games_name ON games (name);

CREATE TABLE IF NOT EXISTS users (
    id UUID PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    salt VARCHAR(255) NOT NULL,
    role VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS game_snapshots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    universe_id BIGINT NOT NULL REFERENCES games (universe_id),
    visits BIGINT,
    playing BIGINT,
    timestamp TIMESTAMPTZ NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_game_snapshots_universe_time ON game_snapshots (universe_id, timestamp);

CREATE TABLE IF NOT EXISTS game_daily_analytics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    universe_id BIGINT NOT NULL REFERENCES games (universe_id),
    date DATE NOT NULL,
    average_playing BIGINT,
    max_visits BIGINT,
    min_playing BIGINT,
    max_playing BIGINT,
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_game_daily_analytics_universe_date UNIQUE (universe_id, date)
);

CREATE INDEX IF NOT EXISTS idx_game_daily_analytics_universe_date ON game_daily_analytics (universe_id, date);

CREATE TABLE IF NOT EXISTS user_radar (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES users (id),
    universe_id BIGINT NOT NULL REFERENCES games (universe_id),
    created_at TIMESTAMPTZ NOT NULL
);
